#pragma once

#include <ntddk.h>

#define SERBERT_DEVICE_NAME     L"\\Device\\Serbert"
#define SERBERT_DOS_DEVICE_NAME L"\\DosDevices\\Serbert"

#define FILE_DEVICE_SERBERT     0x00008271

#define IOCTL_SERBERT_REGISTER_CONTROLLER \
    CTL_CODE(FILE_DEVICE_SERBERT, 0x800, METHOD_BUFFERED, FILE_READ_DATA | FILE_WRITE_DATA)

#define IOCTL_SERBERT_ADD_RULE \
    CTL_CODE(FILE_DEVICE_SERBERT, 0x801, METHOD_BUFFERED, FILE_READ_DATA | FILE_WRITE_DATA)

#define IOCTL_SERBERT_CLEAR_RULES \
    CTL_CODE(FILE_DEVICE_SERBERT, 0x802, METHOD_BUFFERED, FILE_READ_DATA | FILE_WRITE_DATA)

#define IOCTL_SERBERT_GET_STATUS \
    CTL_CODE(FILE_DEVICE_SERBERT, 0x803, METHOD_BUFFERED, FILE_READ_DATA)

#pragma pack(push, 1)

typedef struct _SERBERT_REGISTER_REQUEST {
    ULONG ControllerPid;
} SERBERT_REGISTER_REQUEST, *PSERBERT_REGISTER_REQUEST;

typedef struct _SERBERT_RULE_REQUEST {
    WCHAR ImageName[64];
} SERBERT_RULE_REQUEST, *PSERBERT_RULE_REQUEST;

typedef struct _SERBERT_STATUS_RESPONSE {
    ULONG Version;
    ULONG ActiveRulesCount;
    ULONG BlockedExecutionsCount;
    ULONG ControllerPid;
    BOOLEAN ProcessNotifyActive;
    UCHAR Reserved[3];
} SERBERT_STATUS_RESPONSE, *PSERBERT_STATUS_RESPONSE;

#pragma pack(pop)
